#!/usr/bin/env python3
"""Generate the Blasius reference data for the flat_plate_blasius_of case.

Analytical reference (no measured data involved): the local skin-friction
coefficient of the laminar, zero-pressure-gradient flat-plate boundary
layer from the Blasius similarity solution,

    Cf(x) = 0.664 / sqrt(Re_x),   Re_x = U_inf * x / nu

with this case's U_inf = 1 m/s and nu = 1e-5 m^2/s (Re_x = 1e5 * x[m]).
The constant 0.664 (= 2 * f''(0), f''(0) ~ 0.33206) is the textbook value
(Schlichting & Gersten, "Boundary-Layer Theory"; Blasius 1908).

Outputs (both regenerated by this script; do not hand-edit):
  reference/blasius_cf.csv  -- Cf at x = 0.1 .. 1.0 m (Re_x = 1e4 .. 1e5)
  held_out/qoi.json         -- the four QoI stations x = 0.2/0.5/0.8/1.0 m

Pure Python standard library; run from anywhere:

    python3 generate_reference.py
"""

import csv
import json
import math
from pathlib import Path

CASE_DIR = Path(__file__).resolve().parent

U_INF = 1.0   # m/s, must match 0/U inlet and internalField
NU = 1e-5     # m^2/s, must match constant/transportProperties

# CSV stations: Re_x spans 1e4 .. 1e5 (laminar, below transition ~5e5).
CSV_STATIONS_M = [0.1 * i for i in range(1, 11)]

# QoI stations (a subset of the CSV stations, kept away from both the
# leading-edge singularity and the outlet).
QOI_STATIONS = {
    "cf_x020": 0.2,
    "cf_x050": 0.5,
    "cf_x080": 0.8,
    "cf_x100": 1.0,
}


def blasius_cf(x_m: float) -> float:
    """Local Blasius skin-friction coefficient at station x [m]."""
    re_x = U_INF * x_m / NU
    return 0.664 / math.sqrt(re_x)


def main() -> None:
    csv_path = CASE_DIR / "reference" / "blasius_cf.csv"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["x_m", "re_x", "cf_blasius"])
        for x in CSV_STATIONS_M:
            writer.writerow([f"{x:.1f}", f"{U_INF * x / NU:.6g}", f"{blasius_cf(x):.6g}"])

    qoi_path = CASE_DIR / "held_out" / "qoi.json"
    qoi_path.parent.mkdir(parents=True, exist_ok=True)
    qoi = {name: float(f"{blasius_cf(x):.6g}") for name, x in QOI_STATIONS.items()}
    with qoi_path.open("w", encoding="utf-8") as f:
        json.dump(qoi, f, indent=2)
        f.write("\n")

    print(f"wrote {csv_path.relative_to(CASE_DIR)} ({len(CSV_STATIONS_M)} stations)")
    print(f"wrote {qoi_path.relative_to(CASE_DIR)}: {qoi}")


if __name__ == "__main__":
    main()
