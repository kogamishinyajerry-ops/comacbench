"""gold — cbsk_polygon_b03：在 YZ 平面构造题面规定的 2D 草图并导出 sketch.step。"""
import cadquery as cq

PLANE = cq.Plane.named("YZ")


def w(u, v):
    return PLANE.toWorldCoords((u, v))


edges = []
LINES = [
    ((17.840885, -5.320644), (22.182779, 1.116478)),
    ((22.182779, 1.116478), (22.724408, 8.862135)),
    ((22.724408, 8.862135), (19.320644, 15.840885)),
    ((19.320644, 15.840885), (12.883522, 20.182779)),
    ((12.883522, 20.182779), (5.137865, 20.724408)),
    ((5.137865, 20.724408), (-1.840885, 17.320644)),
    ((-1.840885, 17.320644), (-6.182779, 10.883522)),
    ((-6.182779, 10.883522), (-6.724408, 3.137865)),
    ((-6.724408, 3.137865), (-3.320644, -3.840885)),
    ((-3.320644, -3.840885), (3.116478, -8.182779)),
    ((3.116478, -8.182779), (10.862135, -8.724408)),
    ((10.862135, -8.724408), (17.840885, -5.320644)),
]
for a, b in LINES:
    edges.append(cq.Edge.makeLine(w(*a), w(*b)))

cq.exporters.export(cq.Compound.makeCompound(edges), "sketch.step")
